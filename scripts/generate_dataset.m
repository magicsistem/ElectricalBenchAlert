function manifest = generate_dataset(n_per_cell)
%GENERATE_DATASET Metadata-only v2 development dataset; MATLAB lazy waveform authority.
cfg=eba.config();if nargin<1,n_per_cell=cfg.families_per_cell;end
T=eba.families(n_per_cell,cfg); balance=eba.validateFamilies(T,cfg);
familyHash=eba.hash(jsonencode(table2struct(T)),'text');
sourceFiles={'+eba/config.m','+eba/hash.m','+eba/json.m','+eba/families.m','+eba/waveform.m','+eba/noise.m','+eba/record.m', ...
    '+eba/validateFamilies.m','+eba/fixtureReview.m','+eba/recordId.m','scripts/generate_dataset.m','config/research_v2.json'};
sourceHashes=cellfun(@(p) eba.hash(fullfile(cfg.root,p),'file'),sourceFiles,'UniformOutput',false);
sourceIdentity=eba.hash(strjoin(sourceHashes,''),'text');
folder=fullfile(cfg.output,sprintf('development_dataset_n%d_%s_%s',n_per_cell,familyHash(1:12),sourceIdentity(1:12)));
manifestPath=fullfile(folder,'manifest.json');
if isfile(manifestPath)
    manifest=jsondecode(fileread(manifestPath));
    assert(strcmp(manifest.family_parameters_sha256,familyHash) && strcmp(manifest.generator_source_sha256,sourceIdentity) && ...
        strcmp(manifest.families_csv_sha256,eba.hash(fullfile(folder,'families.csv'),'file')) && ...
        strcmp(manifest.derivatives_csv_sha256,eba.hash(fullfile(folder,'derivatives.csv'),'file')) && ...
        strcmp(manifest.fixture_review_sha256,eba.hash(fullfile(folder,'original_fixture_review.json'),'file')), ...
        'eba:DatasetMutation','Existing development dataset failed its identity check.');
    fprintf('DATASET_V2_DEVELOPMENT_METADATA_READY families=%d derivatives=%d\n',height(T),manifest.n_derived_records); return;
end
assert(~isfolder(folder),'eba:PartialDataset','Incomplete dataset directory exists; preserve it and use a fresh output directory.');
mkdir(folder);
nVariants=1+numel(cfg.snr_db)*cfg.noise_realizations;
V=table('Size',[height(T)*nVariants 7],'VariableTypes',{'string','string','string','double','double','double','double'}, ...
    'VariableNames',{'record_id','family_id','split','requested_snr_db','noise_realization','noise_seed','family_seed'});
k=0;
for i=1:height(T)
    p=jsondecode(T.parameters_json(i)); k=k+1;
    V(k,:)={eba.recordId(T.family_id(i),Inf,0),T.family_id(i),T.split(i),Inf,0, ...
        1000000000+double(cfg.master_seed)+p.family_serial*16+1,T.family_seed(i)};
    for r=1:cfg.noise_realizations
        for snr=cfg.snr_db(:)'
            k=k+1; id=eba.recordId(T.family_id(i),snr,r);
            V(k,:)={id,T.family_id(i),T.split(i),snr,r,1000000000+double(cfg.master_seed)+p.family_serial*16+r,T.family_seed(i)};
        end
    end
end
assert(numel(unique(V.record_id))==height(V),'eba:RecordIdentity','Derivative IDs are not unique.');
writetable(T,fullfile(folder,'families.csv')); writetable(V,fullfile(folder,'derivatives.csv'));
review=eba.fixtureReview(cfg); eba.json(fullfile(folder,'original_fixture_review.json'),review);
manifest=struct('schema_version',cfg.schema_version,'dataset_version',cfg.dataset_version, ...
    'status','development_learning_curve_and_precision_review_pending','scientific_authority','MATLAB', ...
    'families_per_cell',n_per_cell,'n_independent_families',height(T),'n_derived_records',height(V), ...
    'derivatives_per_family',nVariants,'sampling_frequency_hz',cfg.Fs,'clip_duration_s',cfg.clip_duration_s, ...
    'requested_snr_db',cfg.snr_db,'noise_realizations',cfg.noise_realizations,'noise_reference',cfg.noise_reference, ...
    'master_seed',cfg.master_seed,'split_seed',cfg.split_seed,'family_parameters_sha256',familyHash, ...
    'families_csv_sha256',eba.hash(fullfile(folder,'families.csv'),'file'), ...
    'derivatives_csv_sha256',eba.hash(fullfile(folder,'derivatives.csv'),'file'), ...
    'fixture_review_sha256',eba.hash(fullfile(folder,'original_fixture_review.json'),'file'), ...
    'generator_source_sha256',sourceIdentity,'generator_files',{sourceFiles},'generator_file_sha256',{sourceHashes}, ...
    'split_balance',balance,'waveforms_stored',false,'waveform_hash_protocol','SHA-256 little-endian column double via eba.record', ...
    'original630_identity_claimed',false,'final_test_opened',false);
eba.json(manifestPath,manifest);
fprintf('DATASET_V2_DEVELOPMENT_METADATA_READY families=%d derivatives=%d\n',height(T),height(V));
end
